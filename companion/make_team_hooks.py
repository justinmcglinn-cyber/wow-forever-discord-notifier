"""Encrypt the webhooks from a config.toml into the code (forever_notify/team_data.py).

Usage: py -3 make_team_hooks.py [path\\to\\config.toml]   (default: dist\\config.toml)

Writes forever_notify/team_data.py with a fresh random key and the encrypted
webhooks. It's committed, so every build (local or GitHub Actions) is a
ready-to-share team exe. Only webhook_url and [webhooks] are taken.
"""

import base64
import os
import sys
import textwrap
import tomllib
from pathlib import Path

from forever_notify import teamhooks
from forever_notify.setup_wizard import WEBHOOK_PREFIXES

HERE = Path(__file__).resolve().parent


def main(argv: list[str]) -> int:
    source = Path(argv[0]) if argv else HERE / "dist" / "config.toml"
    try:
        raw = tomllib.loads(source.read_text(encoding="utf-8-sig"))
    except (OSError, tomllib.TOMLDecodeError) as e:
        print(f"Could not read {source}: {e}")
        return 1
    main_url = str(raw.get("webhook_url", "")).strip()
    hooks = {k: str(v).strip() for k, v in raw.get("webhooks", {}).items() if str(v).strip()}
    bad = [name for name, url in [("webhook_url", main_url), *hooks.items()] if not url.startswith(WEBHOOK_PREFIXES)]
    if bad:
        print(f"Not a Discord webhook URL in {source}: {', '.join(bad)}")
        return 1

    key = os.urandom(32)
    blob = base64.b64encode(teamhooks.encode(main_url, hooks, key)).decode("ascii")
    assert teamhooks.decode(base64.b64decode(blob), key) == (main_url, hooks)
    lines = "\n".join(f'    "{chunk}"' for chunk in textwrap.wrap(blob, 96))
    target = HERE / "forever_notify" / "team_data.py"
    target.write_text(
        '"""Team webhooks, encrypted. Generated by make_team_hooks.py; re-run it to change them.\n\n'
        "The key is right here, so this only stops casual reading and secret scanners,\n"
        'not anyone with this file or the exe. See teamhooks.py."""\n\n'
        f'KEY = "{key.hex()}"\n\nBLOB = (\n{lines}\n)\n', encoding="utf-8", newline="\n")
    channels = ", ".join(["default"] + sorted(hooks))
    print(f"Encrypted {1 + len(hooks)} webhooks ({channels}) from {source} into {target.relative_to(HERE)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
